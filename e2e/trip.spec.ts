import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => { await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload() })

test('Local Demo 首页、动态 Day、地点攻略和直接路由正常', async ({ page }) => {
  await expect(page).toHaveTitle('GreenNote Travel')
  await expect(page.getByRole('link', { name: 'GreenNote Travel 首页' })).toContainText('GreenNote Travel')
  await expect(page.locator('.release-badge')).toHaveText('V1.0 · Demo')
  await expect(page.getByRole('heading', { name: '示例山海自驾 · 3 Days', level: 1 })).toBeVisible()
  await expect(page.locator('.day-card')).toHaveCount(3)
  await expect(page.getByRole('list', { name: '总路线' }).getByRole('listitem')).toHaveCount(4)
  await page.goto('/day/demo-day-1')
  await expect(page.getByRole('heading', { name: '青屿城 → 海湾步道 → 山居民宿' })).toBeVisible()
  await expect(page.getByRole('img', { name: '几何图形绘制的虚构海湾与步道' })).toBeVisible()
  await page.getByRole('link', { name: '查看完整攻略' }).click()
  await expect(page).toHaveURL(/\/place\/demo-baywalk$/)
  await expect(page.getByRole('heading', { name: '海湾步道', level: 1 })).toBeVisible()
  await expect(page.getByRole('heading', { name: '弹性安排' })).toBeVisible()
  await page.goto('/does-not-exist')
  await expect(page.getByRole('heading', { name: '这里不在计划路线中' })).toBeVisible()
})

