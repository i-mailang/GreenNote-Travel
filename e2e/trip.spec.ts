test('管理员 Local 模式完成保存、预览、发布和备份恢复', async ({ page }) => {
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: '旅行计划管理' })).toBeVisible()
  await page.getByLabel('旅行名称').fill('我的 Demo 草稿')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await expect(page.getByText(/保存成功/)).toBeVisible()
  await page.getByRole('button', { name: '草稿预览' }).click()
  await expect(page.getByText('未发布草稿预览')).toBeVisible()
  await expect(page.getByRole('heading', { name: '我的 Demo 草稿', level: 1 })).toBeVisible()
  await page.getByRole('link', { name: '返回管理页' }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '发布', exact: true }).click()
  await expect(page.getByText(/已发布/).last()).toBeVisible()
  await page.getByRole('button', { name: '备份', exact: true }).click()
  await expect(page.getByText(/修订版/).last()).toBeVisible()
  await expect(page.getByRole('button', { name: '恢复为新修订版' }).first()).toBeVisible()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '我的 Demo 草稿', level: 1 })).toBeVisible()
})

test('320px 无横向溢出并可从 PWA 缓存离线打开公开版', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.evaluate(() => navigator.serviceWorker?.ready)
  await page.reload()
  await page.waitForFunction(() => Boolean(navigator.serviceWorker?.controller))
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: '示例山海自驾 · 3 Days', level: 1 })).toBeVisible()
  await context.setOffline(false)
})
